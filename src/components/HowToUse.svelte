<section class="dont-print">
    <h2>How to Use</h2>
    <div class="instructions">
        <ol>
            <li>Click on the <em>"Choose File"</em> button to upload your photo.</li>
            <li>Adjust the cropping area as needed. Top of the head should touch the top guide line, and the chin should touch the bottom guide line.</li>
            <li>
                Click on the <em>"Crop"</em> button to generate the passport size
                photo.
            </li>
            <li>
                Download the cropped image (630px x 810px) by clicking the <em>"Download"</em>
                button.
            </li>
            <li>
                For printing multiple passport size photos, click the <em>"Printable"</em>
                button to print a 6 x 4 sheet with 6 cropped 2 x 2 images.
            </li>
        </ol>
    </div>
